	def __micro_step(self):
		"""Implementation of __micro_step function.
		"""
		transitioned = -1
		self.__state_conf_vector_position = 0
		state = self.__state_vector[0]
		if state == self.State.health_ideal:
			transitioned = self.__health_ideal_react(transitioned)
		elif state == self.State.health_defective:
			transitioned = self.__health_defective_react(transitioned)
		elif state == self.State.health_erroneous:
			transitioned = self.__health_erroneous_react(transitioned)
		elif state == self.State.health_faulty:
			transitioned = self.__health_faulty_react(transitioned)
		elif state == self.State.health_degraded:
			transitioned = self.__health_degraded_react(transitioned)
		elif state == self.State.health_failed:
			transitioned = self.__health_failed_react(transitioned)
		elif state == self.State.health_malfunctioning:
			transitioned = self.__health_malfunctioning_react(transitioned)
		if self.__state_conf_vector_position < 1:
			state = self.__state_vector[1]
			if state == self.State.belonging_desingaged:
				self.__belonging_desingaged_react(transitioned)
			elif state == self.State.belonging_prepared:
				self.__belonging_prepared_react(transitioned)
			elif state == self.State.belonging_passive:
				self.__belonging_passive_react(transitioned)
			elif state == self.State.belonging_active:
				self.__belonging_active_react(transitioned)
	
	
	def run_cycle(self):
		"""Implementation of run_cycle function.
		"""
		#Performs a 'run to completion' step.
		if self.__is_executing:
			return
		self.__is_executing = True
		next_event = self.__get_next_event()
		if next_event is not None:
			self.__execute_queued_event(next_event)
		condition_0 = True
		while condition_0:
			self.__micro_step()
			self.__clear_in_events()
			condition_0 = False
			next_event = self.__get_next_event()
			if next_event is not None:
				self.__execute_queued_event(next_event)
				condition_0 = True
		self.__is_executing = False
	
	
	def enter(self):
		"""Implementation of enter function.
		"""
		#Activates the state machine.
		if self.__is_executing:
			return
		self.__is_executing = True
		#Default enter sequence for statechart belonging
		self.__enter_sequence_health_default()
		self.__enter_sequence_belonging_default()
		self.__is_executing = False
	
	
	def exit(self):
		"""Implementation of exit function.
		"""
		#Deactivates the state machine.
		if self.__is_executing:
			return
		self.__is_executing = True
		#Default exit sequence for statechart belonging
		self.__exit_sequence_health()
		self.__state_vector[0] = self.State.null_state
		self.__state_conf_vector_position = 0
		self.__exit_sequence_belonging()
		self.__state_vector[1] = self.State.null_state
		self.__state_conf_vector_position = 1
		self.__is_executing = False
	
	
	def trigger_without_event(self):
		"""Implementation of triggerWithoutEvent function.
		"""
		self.run_cycle()
	
